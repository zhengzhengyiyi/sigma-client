ipcMain.handle('instance-launch', async (event, instanceId: string) => {
  // Get current account from storage
  const currentAccount = getCurrentAccount();
  
  if (!currentAccount) {
    return { success: false, error: 'Please login first' };
  }
  
  const username = currentAccount.username;
  const uuid = currentAccount.uuid;
  
  // Get instance details
  const instance = getInstance(instanceId);
  if (!instance) {
    return { success: false, error: 'Instance not found' };
  }
  
  // Check if Minecraft version is downloaded
  const minecraftDir = app.getPath('home') + '/sigma_client';
  const versionDir = `${minecraftDir}/versions/${instance.version}`;
  const clientJar = `${versionDir}/${instance.version}.jar`;
  
  const fs = require('fs');
  if (!fs.existsSync(clientJar)) {
    return { success: false, error: 'Minecraft version not downloaded. Please download it in Settings first.' };
  }
  
  // Update last played time
  updateInstance(instanceId, { lastPlayed: new Date().toISOString() });
  
  // Launch Minecraft
  const result = await launchMinecraft({
    instanceId,
    username,
    uuid,
    memory: instance.memory,
    gameDirectory: minecraftDir
  });
  
  return result;
});
