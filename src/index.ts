// Authentication handlers
ipcMain.handle('auth-login', async (event, credentials: { username: string; password: string }) => {
  // Simple offline login - username only, no password needed
  console.log('Offline auth login requested:', credentials.username);
  
  let username: string;
  if (!credentials.username) {
    // Generate random username if none provided
    const user = createOfflineUser();
    username = user.username;
  } else {
    // Validate and use provided username
    if (!validateOfflineUsername(credentials.username)) {
      throw new Error('Invalid username. Must be 3-16 alphanumeric characters.');
    }
    username = credentials.username;
  }
  
  // Generate UUID for offline user
  const { generateOfflineUUID } = await import('./main/auth/offline-auth');
  const uuid = generateOfflineUUID(username);
  
  // Save to account storage
  const account = addOfflineAccount(username, uuid);
  
  return {
    authenticated: true,
    username: account.username,
    uuid: account.uuid,
    offline: true,
    accountId: account.id
  };
});

ipcMain.handle('auth-microsoft-login', async (event) => {
  try {
    const result = await microsoftAuthenticate(async (message) => {
      event.sender.send('auth-progress', message);
    });
    
    // Save to account storage
    const account = addMicrosoftAccount(
      result.username,
      result.uuid,
      result.accessToken,
      result.refreshToken,
      result.profile
    );
    
    return {
      ...result,
      accountId: account.id
    };
  } catch (error) {
    console.error('Microsoft login failed:', error);
    throw error;
  }
});

